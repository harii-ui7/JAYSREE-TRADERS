// Helper to create clean, responsive SVG product placeholder visuals with high-fidelity industrial styling
function createProductSvg(title: string, category: string, primaryColor: string, secondaryColor: string): string {
  const cleanTitle = title.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const cleanCategory = category.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300" width="100%" height="100%">
      <defs>
        <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
          <stop offset="0%" stop-color="#f8fafc"/>
          <stop offset="100%" stop-color="#e2e8f0"/>
        </linearGradient>
        <linearGradient id="accent" x1="0%" y1="0%" x2="100%" y2="100%">
          <stop offset="0%" stop-color="${primaryColor}"/>
          <stop offset="100%" stop-color="${secondaryColor}"/>
        </linearGradient>
      </defs>
      <rect width="400" height="300" fill="url(#bg)"/>
      <circle cx="200" cy="130" r="70" fill="url(#accent)" opacity="0.12"/>
      <rect x="150" y="80" width="100" height="100" rx="16" fill="url(#accent)" opacity="0.9"/>
      <circle cx="200" cy="130" r="28" fill="#ffffff" opacity="0.95"/>
      <path d="M190 130 L200 118 L210 130 L202 130 L202 142 L198 142 L198 130 Z" fill="${primaryColor}"/>
      <text x="200" y="222" font-family="system-ui, -apple-system, sans-serif" font-size="15" font-weight="700" fill="#0f172a" text-anchor="middle">${cleanTitle}</text>
      <text x="200" y="244" font-family="system-ui, -apple-system, sans-serif" font-size="11" font-weight="600" letter-spacing="1" fill="#64748b" text-anchor="middle">${cleanCategory.toUpperCase()}</text>
    </svg>`.trim();

  // Convert to base64 safely in both browser and node environments
  let b64 = '';
  if (typeof btoa !== 'undefined') {
    b64 = btoa(unescape(encodeURIComponent(svg)));
  } else if (typeof Buffer !== 'undefined') {
    b64 = Buffer.from(svg).toString('base64');
  }
  return `data:image/svg+xml;base64,${b64}`;
}

